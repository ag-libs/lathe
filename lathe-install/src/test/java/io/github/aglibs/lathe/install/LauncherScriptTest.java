package io.github.aglibs.lathe.install;

import static org.assertj.core.api.Assertions.assertThat;

import io.github.aglibs.lathe.core.JavaArgfile;
import io.github.aglibs.lathe.core.LatheLayout;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.concurrent.TimeUnit;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

// Runs the rendered launcher (the .cmd on Windows) on the real JDK, from a launcher dir under a
// path
// with a space and a quote, with an argfile beside it that starts PrintLaunch, so the test checks
// what java is started with, not the text.
class LauncherScriptTest {

  @TempDir Path tmp;

  @Test
  void render_startsTheJdkWithGuardThenWorkspaceOptionsThenTheArgfileBesideIt() throws Exception {
    final Path launcherDir = Files.createDirectories(tmp.resolve("o'neil cache/servers/1.0"));
    final Path launcher = launcherDir.resolve(LatheLayout.LAUNCHER_SCRIPT);
    Files.writeString(launcher, new LauncherScript("1.0", LatheLayout.SERVER_ARGS_FILE).render());
    assertThat(launcher.toFile().setExecutable(true)).isTrue();
    JavaArgfile.write(
        launcherDir,
        launcherDir.resolve(LatheLayout.SERVER_ARGS_FILE),
        PrintLaunch.argfile(),
        JavaArgfile.NATIVE_CHARSET);
    final Path workspace = Files.createDirectories(tmp.resolve("ws/.lathe")).getParent();
    Files.writeString(
        workspace.resolve(LatheLayout.LATHE_DIR).resolve(LatheLayout.JVM_ARGS_FILE),
        "-Dlathe.test.workspace=true\n");

    final var builder =
        new ProcessBuilder(launcher.toString(), "--stdio").directory(workspace.toFile());
    builder.environment().put("LATHE_JAVA_HOME", System.getProperty("java.home"));
    builder.environment().put("LATHE_JVM_OPTS", "-Xmx1g");
    final Process process = builder.start();
    final var output = new String(process.getInputStream().readAllBytes(), StandardCharsets.UTF_8);

    assertThat(process.waitFor(30, TimeUnit.SECONDS)).isTrue();
    assertThat(process.exitValue()).isZero();
    assertThat(output.lines())
        .containsSubsequence(
            "-XX:+DisplayVMOutputToStderr",
            "-Xlog:disable",
            "-Xlog:all=warning:stderr",
            "-Dstdout.encoding=UTF-8",
            "-Dstderr.encoding=UTF-8",
            "-Dlathe.test.workspace=true",
            "-Xmx1g")
        .endsWith("--", "--stdio");
    assertThat(new LauncherScript("1.0", LatheLayout.SERVER_ARGS_FILE).posix())
        .startsWith("#!/bin/sh\n# lathe-server 1.0, generated by lathe:sync; do not edit\n");
  }

  // The render_ test runs the cmd launcher on Windows; this checks the text for what cmd.exe needs.
  @Test
  void cmd_crlfWithChcpFirst_startsJavaWithTheArgfileBesideIt_withoutParenthesizedBlocks() {
    final String script = new LauncherScript("1.0", LatheLayout.SERVER_ARGS_FILE).cmd();
    final List<String> lines = List.of(script.split("\r\n"));

    assertThat(script.replace("\r\n", "")).doesNotContain("\n");
    assertThat(lines)
        .startsWith(
            "@echo off",
            "rem lathe-server 1.0, generated by lathe:sync; do not edit",
            "chcp 65001 >nul")
        .contains(
            "if not defined jhome if exist \".lathe\\java-home\" set /p jhome=<\".lathe\\java-home\"",
            "if exist \".lathe\\jvm.args\" set \"jvm_args=@.lathe\\jvm.args\"",
            "\"%java_bin%\" -XX:+DisplayVMOutputToStderr -Xlog:disable -Xlog:all=warning:stderr"
                + " -Dstdout.encoding=UTF-8 -Dstderr.encoding=UTF-8"
                + " %jvm_args% %LATHE_JVM_OPTS% @\"%~dp0lathe-server.args\" %*",
            "exit /b %ERRORLEVEL%");
    // A ')' in an expanded path (Program Files (x86)) would end a parenthesized block early.
    assertThat(lines).noneMatch(line -> line.contains("(") && line.contains("%"));
  }
}
