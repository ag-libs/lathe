package io.github.aglibs.lathe.install;

import static org.assertj.core.api.Assertions.assertThat;

import io.github.aglibs.lathe.core.IOUtil;
import io.github.aglibs.lathe.core.JavaArgfile;
import io.github.aglibs.lathe.core.LatheLayout;
import io.github.aglibs.validcheck.ValidCheck;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.Map;
import java.util.concurrent.CompletableFuture;
import java.util.concurrent.TimeUnit;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

// Runs the rendered launcher (the .cmd on Windows) on the real JDK, from a launcher dir under a
// path with a space and a quote, with an argfile beside it that starts PrintLaunch, so the test
// checks what java is started with, not the text.
class LauncherScriptTest {

  @TempDir Path tmp;

  private record Run(List<String> stdout, String stderr) {

    Run {
      ValidCheck.check().notNull(stdout, "stdout").notNull(stderr, "stderr").validate();
      stdout = List.copyOf(stdout);
    }
  }

  @Test
  void render_startsTheJdkWithGuardThenWorkspaceOptionsThenTheArgfileBesideIt() throws Exception {
    final Path workspace = workspace("ws");
    final Run run =
        run(
            workspace,
            Map.of("LATHE_JAVA_HOME", System.getProperty("java.home"), "LATHE_JVM_OPTS", "-Xmx1g"));

    assertThat(run.stdout())
        .containsSubsequence(
            "-XX:+DisplayVMOutputToStderr",
            "-Xlog:disable",
            "-Xlog:all=warning:stderr",
            "-Dstdout.encoding=UTF-8",
            "-Dstderr.encoding=UTF-8",
            "-Dlathe.test.workspace=true",
            "-Xmx1g")
        .endsWith("--", "--stdio");
    assertThat(new LauncherScript("1.0", LatheLayout.SERVER_ARGS_FILE).posix())
        .startsWith("#!/bin/sh\n# lathe-server 1.0, generated by lathe:sync; do not edit\n");
  }

  @Test
  void render_startedInAModuleDirectory_readsTheWorkspaceRootLathe() throws Exception {
    // A path with a space, as the root's jvm.args path is now absolute; a java-home without a
    // bin/java, so the launcher names the directory it read before falling back to PATH java.
    final Path workspace = workspace("my ws");
    final Path missingJdk = tmp.resolve("no jdk here");
    Files.writeString(
        workspace.resolve(LatheLayout.LATHE_DIR).resolve(LatheLayout.JAVA_HOME_FILE),
        missingJdk.toString());
    final Path module = Files.createDirectories(workspace.resolve("core/src"));

    final Run run = run(module, Map.of());

    assertThat(run.stdout()).contains("-Dlathe.test.workspace=true").endsWith("--", "--stdio");
    assertThat(run.stderr()).contains(missingJdk.toString());
  }

  // The render_ tests run the cmd launcher on Windows; this checks the text for what cmd.exe needs.
  @Test
  void cmd_crlfWithChcpFirst_startsJavaWithTheArgfileBesideIt_withoutParenthesizedBlocks() {
    final String script = new LauncherScript("1.0", LatheLayout.SERVER_ARGS_FILE).cmd();
    final List<String> lines = List.of(script.split("\r\n"));

    assertThat(script.replace("\r\n", "")).doesNotContain("\n");
    assertThat(lines)
        .startsWith(
            "@echo off",
            "rem lathe-server 1.0, generated by lathe:sync; do not edit",
            "chcp 65001 >nul")
        .contains(
            "if not defined jhome if defined lathe_dir if exist \"%lathe_dir%\\java-home\""
                + " set /p jhome=<\"%lathe_dir%\\java-home\"",
            "if defined lathe_dir if exist \"%lathe_dir%\\jvm.args\""
                + " set jvm_args=@\"%lathe_dir%\\jvm.args\"",
            "\"%java_bin%\" -XX:+DisplayVMOutputToStderr -Xlog:disable -Xlog:all=warning:stderr"
                + " -Dstdout.encoding=UTF-8 -Dstderr.encoding=UTF-8"
                + " %jvm_args% %LATHE_JVM_OPTS% @\"%~dp0lathe-server.args\" %*",
            "exit /b %ERRORLEVEL%");
    // A ')' in an expanded path (Program Files (x86)) would end a parenthesized block early.
    assertThat(lines).noneMatch(line -> line.contains("(") && line.contains("%"));
  }

  // A workspace root whose .lathe/jvm.args sets a marker option.
  private Path workspace(final String name) throws Exception {
    final Path workspace =
        Files.createDirectories(tmp.resolve(name).resolve(LatheLayout.LATHE_DIR));
    Files.writeString(
        workspace.resolve(LatheLayout.JVM_ARGS_FILE), "-Dlathe.test.workspace=true\n");
    return workspace.getParent();
  }

  // Renders the launcher with an argfile that starts PrintLaunch and runs it from `cwd` with
  // `--stdio`.
  private Run run(final Path cwd, final Map<String, String> environment) throws Exception {
    final Path launcherDir = Files.createDirectories(tmp.resolve("o'neil cache/servers/1.0"));
    final Path launcher = launcherDir.resolve(LatheLayout.LAUNCHER_SCRIPT);
    Files.writeString(launcher, new LauncherScript("1.0", LatheLayout.SERVER_ARGS_FILE).render());
    assertThat(launcher.toFile().setExecutable(true)).isTrue();
    JavaArgfile.write(
        launcherDir,
        launcherDir.resolve(LatheLayout.SERVER_ARGS_FILE),
        PrintLaunch.argfile(),
        JavaArgfile.NATIVE_CHARSET);

    final var builder = new ProcessBuilder(launcher.toString(), "--stdio").directory(cwd.toFile());
    builder.environment().remove("LATHE_JAVA_HOME");
    builder.environment().remove("LATHE_JVM_OPTS");
    builder.environment().putAll(environment);
    final Process process = builder.start();
    final CompletableFuture<String> stderr =
        CompletableFuture.supplyAsync(
            () ->
                new String(
                    IOUtil.unchecked(() -> process.getErrorStream().readAllBytes()),
                    StandardCharsets.UTF_8));
    final var stdout = new String(process.getInputStream().readAllBytes(), StandardCharsets.UTF_8);

    assertThat(process.waitFor(30, TimeUnit.SECONDS)).isTrue();
    assertThat(process.exitValue()).isZero();
    return new Run(stdout.lines().toList(), stderr.join());
  }
}
