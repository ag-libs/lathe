package io.github.aglibs.lathe.install;

import io.github.aglibs.lathe.core.LatheFlags;
import io.github.aglibs.lathe.core.LatheLayout;
import io.github.aglibs.lathe.core.Platform;
import io.github.aglibs.validcheck.ValidCheck;

// A server or MCP launcher: it only picks the JDK and starts Java with the argfile beside it, so it
// names no jar path and runs the same from servers/<version>/, latest/ and a workspace's .lathe/.
// The workspace's .lathe/ is the nearest one in the working directory or above it, as the server
// finds it, so a launcher started in a module directory still reads the root's. The JDK is
// LATHE_JAVA_HOME, else the build JDK in .lathe/java-home, else PATH java. stdout is the LSP
// channel, so the guard sends JVM startup errors and -Xlog output to stderr, and both streams are
// UTF-8. The guard comes first, so the workspace's own options win: .lathe/jvm.args, then
// LATHE_JVM_OPTS. The argfile comes last; it ends with the entry point.
public record LauncherScript(String version, String argfile) {

  private static final String STDOUT_GUARD =
      "-XX:+DisplayVMOutputToStderr -Xlog:disable -Xlog:all=warning:stderr %s"
          .formatted(String.join(" ", LatheFlags.UTF8_OUTPUT_JVM_ARGS));

  public LauncherScript {
    ValidCheck.check().notBlank(version, "version").notBlank(argfile, "argfile").validate();
  }

  public String render() {
    return Platform.WINDOWS ? cmd() : posix();
  }

  public String posix() {
    final String lathe = LatheLayout.LATHE_DIR;
    return """
        #!/bin/sh
        # lathe-server %s, generated by lathe:sync; do not edit
        lathe_dir=
        dir="$PWD"
        while :; do
          if [ -d "$dir/%s" ]; then
            lathe_dir="$dir/%s"
            break
          fi
          parent="$(dirname "$dir")"
          [ "$parent" = "$dir" ] && break
          dir="$parent"
        done
        jhome="${LATHE_JAVA_HOME:-}"
        if [ -z "$jhome" ] && [ -n "$lathe_dir" ] && [ -r "$lathe_dir/%s" ]; then
          jhome="$(cat "$lathe_dir/%s")"
        fi
        java_bin=java
        if [ -n "$jhome" ]; then
          if [ -x "$jhome/bin/java" ]; then
            java_bin="$jhome/bin/java"
          else
            echo "lathe: no bin/java under $jhome; using PATH java" >&2
          fi
        fi
        argfile="$(dirname "$0")/%s"
        if [ -n "$lathe_dir" ] && [ -r "$lathe_dir/%s" ]; then
          set -- "@$lathe_dir/%s" ${LATHE_JVM_OPTS:-} "@$argfile" "$@"
        else
          set -- ${LATHE_JVM_OPTS:-} "@$argfile" "$@"
        fi
        exec "$java_bin" %s "$@"
        """
        .formatted(
            version,
            lathe,
            lathe,
            LatheLayout.JAVA_HOME_FILE,
            LatheLayout.JAVA_HOME_FILE,
            argfile,
            LatheLayout.JVM_ARGS_FILE,
            LatheLayout.JVM_ARGS_FILE,
            STDOUT_GUARD);
  }

  // chcp 65001 first, so a non-ASCII path in the script reads right on any console code page.
  // Labels, not parenthesized blocks, wherever a path is expanded: a ')' in one (Program Files
  // (x86)) would end the block early. CRLF, since cmd.exe misparses labels in LF files.
  public String cmd() {
    return """
        @echo off
        rem lathe-server %s, generated by lathe:sync; do not edit
        chcp 65001 >nul
        setlocal
        set "lathe_dir="
        set "dir=%%CD%%"
        :find
        if exist "%%dir%%\\%s\\" set "lathe_dir=%%dir%%\\%s"
        if defined lathe_dir goto found
        call :up "%%dir%%\\.."
        if "%%up%%"=="%%dir%%" goto found
        set "dir=%%up%%"
        goto find
        :found
        set "jhome=%%LATHE_JAVA_HOME%%"
        if not defined jhome if defined lathe_dir if exist "%%lathe_dir%%\\%s" set /p jhome=<"%%lathe_dir%%\\%s"
        set "java_bin=java"
        if not defined jhome goto args
        if not exist "%%jhome%%\\bin\\java.exe" goto nojava
        set "java_bin=%%jhome%%\\bin\\java.exe"
        goto args
        :nojava
        echo lathe: no bin\\java.exe under "%%jhome%%"; using PATH java 1>&2
        :args
        set "jvm_args="
        if defined lathe_dir if exist "%%lathe_dir%%\\%s" set jvm_args=@"%%lathe_dir%%\\%s"
        "%%java_bin%%" %s %%jvm_args%% %%LATHE_JVM_OPTS%% @"%%~dp0%s" %%*
        exit /b %%ERRORLEVEL%%
        :up
        set "up=%%~f1"
        exit /b 0
        """
        .formatted(
            version,
            LatheLayout.LATHE_DIR,
            LatheLayout.LATHE_DIR,
            LatheLayout.JAVA_HOME_FILE,
            LatheLayout.JAVA_HOME_FILE,
            LatheLayout.JVM_ARGS_FILE,
            LatheLayout.JVM_ARGS_FILE,
            STDOUT_GUARD,
            argfile)
        .replace("\n", "\r\n");
  }
}
