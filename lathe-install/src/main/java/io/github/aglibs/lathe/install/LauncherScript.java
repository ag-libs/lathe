package io.github.aglibs.lathe.install;

import io.github.aglibs.lathe.core.LatheLayout;
import io.github.aglibs.validcheck.ValidCheck;

// A server or MCP launcher: it only picks the JDK and starts Java with the argfile beside it, so it
// names no jar path and runs the same from servers/<version>/, latest/ and a workspace's .lathe/.
public record LauncherScript(String version, String argfile) {

  public LauncherScript {
    ValidCheck.check().notBlank(version, "version").notBlank(argfile, "argfile").validate();
  }

  // The JDK is LATHE_JAVA_HOME, else the build JDK in .lathe/java-home (relative to the server cwd,
  // the workspace root), else PATH java. stdout is the LSP channel, so the guard sends JVM startup
  // errors and -Xlog output to stderr. It comes first, so the workspace's own options win:
  // .lathe/jvm.args, then LATHE_JVM_OPTS. The argfile comes last; it ends with the entry point.
  public String posix() {
    final var javaHome = "%s/%s".formatted(LatheLayout.LATHE_DIR, LatheLayout.JAVA_HOME_FILE);
    final var jvmArgs = "%s/%s".formatted(LatheLayout.LATHE_DIR, LatheLayout.JVM_ARGS_FILE);
    return """
        #!/bin/sh
        # lathe-server %s, generated by lathe:sync; do not edit
        jhome="${LATHE_JAVA_HOME:-}"
        if [ -z "$jhome" ] && [ -r %s ]; then
          jhome="$(cat %s)"
        fi
        java_bin=java
        if [ -n "$jhome" ]; then
          if [ -x "$jhome/bin/java" ]; then
            java_bin="$jhome/bin/java"
          else
            echo "lathe: no bin/java under $jhome; using PATH java" >&2
          fi
        fi
        jvm_args=
        if [ -r %s ]; then
          jvm_args=@%s
        fi
        exec "$java_bin" -XX:+DisplayVMOutputToStderr -Xlog:disable -Xlog:all=warning:stderr \\
          $jvm_args ${LATHE_JVM_OPTS:-} @"$(dirname "$0")/%s" "$@"
        """
        .formatted(version, javaHome, javaHome, jvmArgs, jvmArgs, argfile);
  }
}
