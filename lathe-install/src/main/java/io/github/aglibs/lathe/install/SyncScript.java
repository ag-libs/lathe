package io.github.aglibs.lathe.install;

import io.github.aglibs.lathe.core.FileUtil;
import io.github.aglibs.lathe.core.LatheFlags;
import io.github.aglibs.lathe.core.LatheLayout;
import io.github.aglibs.lathe.core.Platform;
import io.github.aglibs.validcheck.ValidCheck;
import java.io.IOException;
import java.nio.file.Path;
import java.util.List;
import java.util.stream.Collectors;
import java.util.stream.Stream;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

// .lathe/lathe-sync.sh [--tests] [module ...], rendered from the build that ran: the tool and JDK
// are that build's own, so the script chooses nothing. A front-end only fills this in; testsGoals
// and moduleArgs are both empty when it ignores arguments (OpenJDK re-reads the whole build).
// Everything but fixedArgs is spliced in unquoted, so those tokens must not contain whitespace.
public record SyncScript(
    Path tool,
    Path javaHome,
    List<String> fixedArgs,
    List<String> goals,
    List<String> testsGoals,
    List<String> moduleArgs,
    List<String> afterModules) {

  private static final Logger LOG = LoggerFactory.getLogger(SyncScript.class);

  public SyncScript {
    fixedArgs = List.copyOf(fixedArgs);
    goals = List.copyOf(goals);
    testsGoals = List.copyOf(testsGoals);
    moduleArgs = List.copyOf(moduleArgs);
    afterModules = List.copyOf(afterModules);
    ValidCheck.check()
        .notNull(tool, "tool")
        .when(tool != null, v -> v.assertTrue(tool.isAbsolute(), "tool must be an absolute path"))
        .notNull(javaHome, "javaHome")
        .when(
            javaHome != null,
            v -> v.assertTrue(javaHome.isAbsolute(), "javaHome must be an absolute path"))
        .notEmpty(goals, "goals")
        .assertTrue(
            testsGoals.isEmpty() == moduleArgs.isEmpty(),
            "testsGoals and moduleArgs must be both set or both empty")
        .assertTrue(
            moduleArgs.isEmpty() || moduleArgs.contains(LatheFlags.SYNC_MODULE_TOKEN),
            "moduleArgs must contain %s".formatted(LatheFlags.SYNC_MODULE_TOKEN))
        .assertTrue(
            Stream.of(goals, testsGoals, moduleArgs, afterModules)
                .flatMap(List::stream)
                .noneMatch(arg -> arg.isBlank() || arg.chars().anyMatch(Character::isWhitespace)),
            "args other than fixedArgs are not quoted, so they must not contain whitespace")
        .validate();
  }

  public String render() {
    return Platform.WINDOWS ? cmd() : posix();
  }

  // Rewritten only when it changed, so a sync that changes nothing leaves its mtime alone.
  public void write(final Path workspaceRoot) {
    final var latheDir = workspaceRoot.resolve(LatheLayout.LATHE_DIR);
    final var file = latheDir.resolve(LatheLayout.SYNC_SCRIPT);
    try {
      if (FileUtil.writeIfChanged(latheDir, file, render(), true)) {
        LOG.info("[sync] wrote %s".formatted(file));
      }
    } catch (final IOException e) {
      throw new SyncException("lathe:sync failed to write %s".formatted(file), e);
    }
  }

  public String posix() {
    return """
        #!/bin/sh
        # Generated by lathe:sync from the last build -- do not edit. Usage: %s [%s] [module ...]
        cd "$(dirname "$0")/.." || exit 1
        tool=%s
        if [ ! -x "$tool" ]; then
          echo "lathe-sync: $tool not found; run a Lathe-enabled build to regenerate this script" >&2
          exit 1
        fi
        %sset -- "$tool" %s
        echo "lathe-sync: $*" >&2
        export JAVA_HOME=%s
        exec "$@"
        """
        .formatted(
            LatheLayout.syncScriptCommand(false),
            LatheLayout.SYNC_TESTS_FLAG,
            quote(tool.toString()),
            posixArguments(),
            posixCommand(),
            quote(javaHome.toString()));
  }

  private String posixArguments() {
    if (moduleArgs.isEmpty()) {
      return """
          if [ $# -gt 0 ]; then
            echo "lathe-sync: arguments ignored; this sync always re-reads the whole build" >&2
          fi
          """;
    }

    final String upstream =
        afterModules.isEmpty()
            ? ""
            : """
              if [ -n "$scope" ]; then
                scope="$scope %s"
              fi
              """
                .formatted(String.join(" ", afterModules));
    return """
        goal="%s"
        if [ "$1" = "%s" ]; then
          goal="%s"
          shift
        fi
        scope=
        for module in "$@"; do
          scope="$scope %s"
        done
        %s"""
        .formatted(
            String.join(" ", goals),
            LatheLayout.SYNC_TESTS_FLAG,
            String.join(" ", testsGoals),
            String.join(" ", moduleArgs).replace(LatheFlags.SYNC_MODULE_TOKEN, "$module"),
            upstream);
  }

  // Goals before the module scope: a Gradle task option must follow its task, and Maven takes
  // -pl/-am anywhere.
  private String posixCommand() {
    final List<String> variable = moduleArgs.isEmpty() ? goals : List.of("$goal", "$scope");
    return Stream.concat(fixedArgs.stream().map(SyncScript::quote), variable.stream())
        .collect(Collectors.joining(" "));
  }

  private static String quote(final String value) {
    return "'%s'".formatted(value.replace("'", "'\\''"));
  }

  // Labels, not parenthesized blocks, wherever a path or argument is expanded: a ')' in one
  // (Program Files (x86)) would end the block early. call, so control comes back for exit /b;
  // CRLF, since cmd.exe misparses labels in LF files.
  public String cmd() {
    final String command = cmdCommand();
    return """
        @echo off
        rem Generated by lathe:sync from the last build -- do not edit. Usage: %s [%s] [module ...]
        chcp 65001 >nul
        setlocal
        cd /d "%%~dp0.." || exit /b 1
        set "tool=%s"
        if exist "%%tool%%" goto found
        echo lathe-sync: "%%tool%%" not found; run a Lathe-enabled build to regenerate this script 1>&2
        exit /b 1
        :found
        %sset "JAVA_HOME=%s"
        echo lathe-sync: "%%tool%%" %s 1>&2
        call "%%tool%%" %s
        exit /b %%ERRORLEVEL%%
        """
        .formatted(
            LatheLayout.syncScriptCommand(true),
            LatheLayout.SYNC_TESTS_FLAG,
            batch(tool.toString()),
            cmdArguments(),
            batch(javaHome.toString()),
            command,
            command)
        .replace("\n", "\r\n");
  }

  private String cmdArguments() {
    if (moduleArgs.isEmpty()) {
      return """
          if not "%~1"=="" echo lathe-sync: arguments ignored; this sync always re-reads the whole build 1>&2
          """;
    }

    final String upstream =
        afterModules.isEmpty()
            ? ""
            : "if defined scope set \"scope=%%scope%% %s\"\n"
                .formatted(batch(String.join(" ", afterModules)));
    return """
        set "goal=%s"
        if not "%%~1"=="%s" goto modules
        set "goal=%s"
        shift
        :modules
        set "scope="
        :next
        if "%%~1"=="" goto run
        set "scope=%%scope%% %s"
        shift
        goto next
        :run
        %s"""
        .formatted(
            batch(String.join(" ", goals)),
            LatheLayout.SYNC_TESTS_FLAG,
            batch(String.join(" ", testsGoals)),
            batch(String.join(" ", moduleArgs)).replace(LatheFlags.SYNC_MODULE_TOKEN, "%~1"),
            upstream);
  }

  private String cmdCommand() {
    final List<String> variable =
        moduleArgs.isEmpty()
            ? goals.stream().map(SyncScript::batch).toList()
            : List.of("%goal%", "%scope%");
    return Stream.concat(
            fixedArgs.stream().map(arg -> "\"%s\"".formatted(batch(arg))), variable.stream())
        .collect(Collectors.joining(" "));
  }

  // A literal in a batch file: '%' starts a variable, so it is doubled.
  private static String batch(final String value) {
    return value.replace("%", "%%");
  }
}
