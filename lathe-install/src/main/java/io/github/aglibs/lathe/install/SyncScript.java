package io.github.aglibs.lathe.install;

import io.github.aglibs.lathe.core.LatheFlags;
import io.github.aglibs.lathe.core.LatheLayout;
import io.github.aglibs.validcheck.ValidCheck;
import java.nio.file.Path;
import java.util.List;
import java.util.stream.Collectors;
import java.util.stream.Stream;

// .lathe/lathe-sync.sh [--tests] [module ...], rendered from the build that ran: the tool and JDK
// are that build's own, so the script chooses nothing. A front-end only fills this in; testsGoals
// and moduleArgs are both empty when it ignores arguments (OpenJDK re-reads the whole build).
// Everything but fixedArgs is spliced in unquoted, so those tokens must not contain whitespace.
public record SyncScript(
    Path tool,
    Path javaHome,
    List<String> fixedArgs,
    List<String> goals,
    List<String> testsGoals,
    List<String> moduleArgs,
    List<String> afterModules) {

  public SyncScript {
    fixedArgs = List.copyOf(fixedArgs);
    goals = List.copyOf(goals);
    testsGoals = List.copyOf(testsGoals);
    moduleArgs = List.copyOf(moduleArgs);
    afterModules = List.copyOf(afterModules);
    ValidCheck.check()
        .notNull(tool, "tool")
        .when(tool != null, v -> v.assertTrue(tool.isAbsolute(), "tool must be an absolute path"))
        .notNull(javaHome, "javaHome")
        .when(
            javaHome != null,
            v -> v.assertTrue(javaHome.isAbsolute(), "javaHome must be an absolute path"))
        .notEmpty(goals, "goals")
        .assertTrue(
            testsGoals.isEmpty() == moduleArgs.isEmpty(),
            "testsGoals and moduleArgs must be both set or both empty")
        .assertTrue(
            moduleArgs.isEmpty() || moduleArgs.contains(LatheFlags.SYNC_MODULE_TOKEN),
            "moduleArgs must contain %s".formatted(LatheFlags.SYNC_MODULE_TOKEN))
        .assertTrue(
            Stream.of(goals, testsGoals, moduleArgs, afterModules)
                .flatMap(List::stream)
                .noneMatch(arg -> arg.isBlank() || arg.chars().anyMatch(Character::isWhitespace)),
            "args other than fixedArgs are not quoted, so they must not contain whitespace")
        .validate();
  }

  public String posix() {
    return """
        #!/bin/sh
        # Generated by lathe:sync from the last build -- do not edit. Usage: %s [%s] [module ...]
        cd "$(dirname "$0")/.." || exit 1
        tool=%s
        if [ ! -x "$tool" ]; then
          echo "lathe-sync: $tool not found; run a Lathe-enabled build to regenerate this script" >&2
          exit 1
        fi
        %sset -- "$tool" %s
        echo "lathe-sync: $*" >&2
        export JAVA_HOME=%s
        exec "$@"
        """
        .formatted(
            LatheLayout.SYNC_SCRIPT_COMMAND,
            LatheLayout.SYNC_TESTS_FLAG,
            quote(tool.toString()),
            posixArguments(),
            posixCommand(),
            quote(javaHome.toString()));
  }

  private String posixArguments() {
    if (moduleArgs.isEmpty()) {
      return """
          if [ $# -gt 0 ]; then
            echo "lathe-sync: arguments ignored; this sync always re-reads the whole build" >&2
          fi
          """;
    }

    final String upstream =
        afterModules.isEmpty()
            ? ""
            : """
              if [ -n "$scope" ]; then
                scope="$scope %s"
              fi
              """
                .formatted(String.join(" ", afterModules));
    return """
        goal="%s"
        if [ "$1" = "%s" ]; then
          goal="%s"
          shift
        fi
        scope=
        for module in "$@"; do
          scope="$scope %s"
        done
        %s"""
        .formatted(
            String.join(" ", goals),
            LatheLayout.SYNC_TESTS_FLAG,
            String.join(" ", testsGoals),
            String.join(" ", moduleArgs).replace(LatheFlags.SYNC_MODULE_TOKEN, "$module"),
            upstream);
  }

  private String posixCommand() {
    final List<String> variable = moduleArgs.isEmpty() ? goals : List.of("$scope", "$goal");
    return Stream.concat(fixedArgs.stream().map(SyncScript::quote), variable.stream())
        .collect(Collectors.joining(" "));
  }

  private static String quote(final String value) {
    return "'%s'".formatted(value.replace("'", "'\\''"));
  }
}
